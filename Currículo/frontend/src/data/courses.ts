/**
 * Normaliza string para chave determinística de deduplicação
 */

const normalizeKey = (str: string): string => {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, '');
};

/**
 * Função determinística de deduplicação de cursos
 * Chave: normalize(title) + normalize(institution) + workloadHours + issuedAt
 */
export function deduplicateCourses(coursesList: Course[]): Course[] {
  const seenKeys = new Set<string>();
  const uniqueList: Course[] = [];

  for (const course of coursesList) {
    const titleKey = normalizeKey(course.title);
    const instKey = normalizeKey(course.institution);
    const hoursKey = course.workloadHours ? `${course.workloadHours}h` : 'nohours';
    const dateKey = course.issuedAt ?? 'nodate';

    const dedupeKey = `${titleKey}_${instKey}_${hoursKey}_${dateKey}`;

    if (!seenKeys.has(dedupeKey)) {
      seenKeys.add(dedupeKey);
      uniqueList.push(course);
    }
  }

  return uniqueList;
}

